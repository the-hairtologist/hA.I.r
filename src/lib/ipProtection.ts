/**
 * Disable right-click context menu (optional - can be annoying to users)
 */
export const disableRightClick = (enable: boolean = true) => {
  if (enable && process.env.NODE_ENV === 'production') {
    document.addEventListener('contextmenu', (e) => {
      e.preventDefault();
      return false;
    });
  }
};

/**
 * Disable text selection on proprietary elements
 */
export const protectElement = (element: HTMLElement) => {
  element.style.userSelect = 'none';
  element.style.webkitUserSelect = 'none';
  element.setAttribute('unselectable', 'on');
};

/**
 * Obfuscate sensitive data in logs
 */
export const obfuscate = (data: string): string => {
  if (data.length <= 4) return '****';
  return data.slice(0, 2) + '*'.repeat(data.length - 4) + data.slice(-2);
};

/**
 * Generate unique fingerprint for tracking
 */
export const generateFingerprint = async (): Promise<string> => {
  const data = [
    navigator.userAgent,
    navigator.language,
    screen.colorDepth,
    screen.width,
    screen.height,
    new Date().getTimezoneOffset(),
    navigator.hardwareConcurrency,
  ].join('|');
  
  const encoder = new TextEncoder();
  const dataBuffer = encoder.encode(data);
  const hashBuffer = await crypto.subtle.digest('SHA-256', dataBuffer);
  const hashArray = Array.from(new Uint8Array(hashBuffer));
  return hashArray.map(b => b.toString(16).padStart(2, '0')).join('');
};

