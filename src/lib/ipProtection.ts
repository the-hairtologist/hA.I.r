/**
 * Adds watermark to AI-generated content
 */
export const watermarkContent = (content: string, userId?: string): string => {
  const timestamp = new Date().toISOString();
  const id = userId ? ` | User: ${userId.slice(0, 8)}` : "";
  return `${content}\n\n---\n*Generated by hA.I.r™ on ${timestamp}${id}*`;
};

/**
 * Detects suspicious activity patterns
 */
export const detectSuspiciousActivity = (): boolean => {
  // Check for dev tools
  const isDevTools = /./;
  isDevTools.toString = function() {
    return "DevTools detected";
  };
  
  // Check for automated access patterns
  const isAutomated = navigator.webdriver || 
                      (window as any).__nightmare || 
                      (window as any).phantom;
  
  return !!isAutomated;
};

/**
 * Console protection
 */
export const protectConsole = () => {
  if (process.env.NODE_ENV === 'production') {
    const noop = () => {};
    const methods = ['log', 'debug', 'info', 'warn', 'error'] as const;
    
    methods.forEach(method => {
      console[method] = noop;
    });
  }
};

